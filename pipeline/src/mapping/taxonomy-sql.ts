import { existsSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { CATEGORIES, type CategorySlug } from '../agent/taxonomy.js'
import type { Dictionary } from './dictionary.js'
import { refineCategory } from './milk.js'
import { DEFAULT_PUBLISH_CATEGORIES } from './scope.js'

type Primitive = string | number
type FilterDefinition = { key: string; label: string; type: 'multi-select'; options: Primitive[] }

const compare = (a: Primitive, b: Primitive) => (typeof a === 'number' && typeof b === 'number' ? a - b : String(a) < String(b) ? -1 : String(a) > String(b) ? 1 : 0)

/**
 * Go трактует `categories.filterSchema` как allowlist: multi-select без непустого `options` отбрасывается,
 * а в запросе принимаются только перечисленные значения. Поэтому options берутся из закоммиченного словаря
 * (значения, реально существующие у карточек категории); API дополнительно пересекает их с текущим snapshot.
 * Категория карточки считается через refineCategory; фильтр с `allow` дополнительно ограничен курированным списком.
 */
export function filterSchemaFor(dict: Dictionary, slug: CategorySlug): { filters: FilterDefinition[] } {
  const category = CATEGORIES.find((c) => c.slug === slug)
  if (!category) throw new Error(`unknown category ${slug}`)
  const cards = Object.values(dict.canonicals).filter((c) => refineCategory(c.category, c.name, c.attributes.fatPercent) === slug)
  const filters: FilterDefinition[] = []
  for (const f of category.filters) {
    const allow = (f as { allow?: readonly Primitive[] }).allow
    const values = new Set<Primitive>()
    for (const card of cards) {
      const value = f.key === 'brand' ? card.brand : (card.attributes as Record<string, number | undefined>)[f.key]
      if (value !== null && value !== undefined && (!allow || allow.includes(value))) values.add(value)
    }
    if (values.size > 0) filters.push({ key: f.key, label: f.label, type: 'multi-select', options: [...values].sort(compare) })
  }
  return { filters }
}

/** Тот же allowlist-контракт, что в Go (`definitions`): multi-select без непустого массива примитивов не будет отдан API */
export function assertServableSchema(slug: string, schema: { filters: { key: string; type: string; options?: unknown }[] }): void {
  for (const f of schema.filters) {
    if (f.type !== 'multi-select') continue
    const o = f.options
    if (!Array.isArray(o) || o.length === 0) throw new Error(`${slug}.${f.key}: multi-select without options is dropped by the API`)
    if (!o.every((v) => typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean')) throw new Error(`${slug}.${f.key}: options must be primitives`)
    if (new Set(o).size !== o.length) throw new Error(`${slug}.${f.key}: duplicate options`)
  }
}

const sqlString = (s: string) => `'${s.replaceAll("'", "''")}'`

export function buildTaxonomyMigration(dict: Dictionary): string {
  const rows = DEFAULT_PUBLISH_CATEGORIES.map((slug) => {
    const category = CATEGORIES.find((c) => c.slug === slug)!
    const filterSchema = filterSchemaFor(dict, slug)
    assertServableSchema(slug, filterSchema)
    const schema = JSON.stringify(filterSchema)
    return ` (${sqlString(`cat-${slug}`)},${sqlString(slug)},${sqlString(category.name)},${sqlString(schema)})`
  })
  return [
    '-- Shymkent catalog taxonomy. Data-only, idempotent, no DDL.',
    '-- GENERATED by `pnpm taxonomy:sql` from data/mapping/dictionary.json; do not edit by hand; a committed taxonomy migration is never changed, a dictionary change gets a new migration (pipeline/test/taxonomy.test.ts checks it).',
    '-- Existing rows keep their id; name and filterSchema are set deterministically. Legacy `other` is not touched.',
    'BEGIN;',
    "SET LOCAL lock_timeout = '5s';",
    "SET LOCAL statement_timeout = '30s';",
    '',
    'INSERT INTO public.categories (id, slug, name, "filterSchema") VALUES',
    rows.join(',\n'),
    'ON CONFLICT (slug) DO UPDATE SET name = EXCLUDED.name, "filterSchema" = EXCLUDED."filterSchema";',
    'COMMIT;',
    '',
  ].join('\n')
}

const TAXONOMY_SUFFIX = '_shymkent_taxonomy'
const STAMP = /^([0-9]{14})_/

const pad = (n: number, w = 2) => String(n).padStart(w, '0')
const stamp = (d: Date) =>
  `${d.getUTCFullYear()}${pad(d.getUTCMonth() + 1)}${pad(d.getUTCDate())}${pad(d.getUTCHours())}${pad(d.getUTCMinutes())}${pad(d.getUTCSeconds())}`
const parseStamp = (s: string) =>
  new Date(Date.UTC(+s.slice(0, 4), +s.slice(4, 6) - 1, +s.slice(6, 8), +s.slice(8, 10), +s.slice(10, 12), +s.slice(12, 14)))

/** Путь к самой поздней миграции таксономии (`*_shymkent_taxonomy/migration.sql`) или null. Применённые миграции не редактируются */
export function latestTaxonomyMigration(migrationsDir: string): string | null {
  if (!existsSync(migrationsDir)) return null
  const names = readdirSync(migrationsDir).filter((n) => STAMP.test(n) && n.endsWith(TAXONOMY_SUFFIX)).sort()
  const last = names.at(-1)
  return last ? join(migrationsDir, last, 'migration.sql') : null
}

/**
 * Путь новой миграции таксономии: метка UTC YYYYMMDDHHMMSS. Метка не раньше самой поздней существующей миграции
 * (иначе Prisma применит её вне порядка): берём позднее из now и «последняя миграция + 1 с».
 */
export function newTaxonomyMigrationPath(migrationsDir: string, now: Date): string {
  const existing = existsSync(migrationsDir) ? readdirSync(migrationsDir).flatMap((n) => STAMP.exec(n)?.[1] ?? []).sort() : []
  const last = existing.at(-1)
  const floor = last ? new Date(parseStamp(last).getTime() + 1000) : now
  const at = floor.getTime() > now.getTime() ? floor : now
  return join(migrationsDir, `${stamp(at)}${TAXONOMY_SUFFIX}`, 'migration.sql')
}
