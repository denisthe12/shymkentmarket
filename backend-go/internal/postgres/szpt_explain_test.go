// szptExplainPath is the release-gate script (plan Task 10): EXPLAIN (ANALYZE, BUFFERS) of the exact SZPT
// products query the API runs. It is generated from szptProductsSQL, szptOrder and szpt.Groups, so it cannot
// drift from the code; regenerate with UPDATE_SZPT_EXPLAIN=1.
var szptExplainPath = filepath.Join("..", "..", "..", "ops", "postgres", "szpt", "szpt_members_explain.sql")

// szptExplainGroups: one live group and one weighted group, each with its default sort.
var szptExplainGroups = []string{"rice", "potatoes"}

func szptExplainScript() (string, error) {
	rules, err := szptRules()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(`-- GENERATED by TestSzptExplainScript (backend-go/internal/postgres/szpt_explain_test.go). Do not edit.
-- Regenerate: cd backend-go && UPDATE_SZPT_EXPLAIN=1 go test ./internal/postgres -run TestSzptExplainScript
--
-- Release gate for SZPT weighted goods (plan Task 10): EXPLAIN (ANALYZE, BUFFERS) of the SZPT products query
-- exactly as the API sends it (szptMembersSQL + page + default ORDER BY, LIMIT 24 OFFSET 0, all group rules
-- as $1, latest published snapshot as $2) for one live and one weighted group.
-- Run as the API login role (export its connection as API_DATABASE_URL), never during the 01:00 / 13:00 UTC sync:
--   node ops/postgres/psql-run.mjs szpt-explain
-- Read-only: one REPEATABLE READ READ ONLY transaction, statement_timeout 60 s, ROLLBACK at the end.
-- Each query runs twice; judge by the "Execution Time" of the second (warm) run.

\set ON_ERROR_STOP 1
BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY;
SET LOCAL statement_timeout = '60s';

\echo '=== Role (expect api_reader = t, reads_raw_products = f) ==='
SELECT current_user AS role,
       pg_has_role(current_user, to_regrole('aktau_api_reader'), 'MEMBER') AS api_reader,
       has_table_privilege('public.raw_products', 'SELECT') AS reads_raw_products;

SELECT id AS snapshot_id FROM public.snapshots
WHERE status = 'published' AND "publishedAt" IS NOT NULL ORDER BY "publishedAt" DESC, id DESC LIMIT 1 \gset
\echo 'latest published snapshot:' :snapshot_id

`)
	fmt.Fprintf(&b, "SELECT '%s' AS rules \\gset\n", strings.ReplaceAll(rules, "'", "''"))
	for _, slug := range szptExplainGroups {
		rule, ok := szpt.Lookup(slug)
		if !ok {
			return "", fmt.Errorf("unknown group %s", slug)
		}
		order, err := szptOrder(rule.DefaultSort())
		if err != nil {
			return "", err
		}
		name := "szpt_" + strings.ReplaceAll(slug, "-", "_")
		fmt.Fprintf(&b, "\nPREPARE %s(jsonb,text,text,numeric[],bigint,bigint,numeric) AS\n%s%s LIMIT $5 OFFSET $6;\n",
			name, szptProductsSQL, order)
		fmt.Fprintf(&b, "\\echo '=== %s (weighted=%v, sort %s, first page): run 1 (cold), run 2 (warm) ==='\n",
			slug, rule.Weighted, rule.DefaultSort())
		for range 2 {
			fmt.Fprintf(&b, "EXPLAIN (ANALYZE, BUFFERS) EXECUTE %s(:'rules', :'snapshot_id', '%s', '{}', 24, 0, %d);\n",
				name, slug, rule.Unit.Factor())
		}
	}
	b.WriteString("\nROLLBACK;\n")
	return b.String(), nil
}

func TestSzptExplainScript(t *testing.T) {
	want, err := szptExplainScript()
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("UPDATE_SZPT_EXPLAIN") == "1" {
		if err := os.WriteFile(szptExplainPath, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(szptExplainPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatalf("%s is stale; regenerate with UPDATE_SZPT_EXPLAIN=1 go test ./internal/postgres -run TestSzptExplainScript", szptExplainPath)
	}
}
